----------------------(NUMBER FUNCTIONS)-----------------------


SELECT
	10.12345,1,
	ROUND(10.12345,1) AS ROUNDED_VALUE_as_1,
	ROUND(10.12345,2) AS ROUNDED_VALUE_as_2,
	ROUND(10.12345,3) AS ROUNDED_VALUE_as_3,
	ROUND(10.12345,4) AS ROUNDED_VALUE_as_4,
	ROUND(10.9345,-0) AS ROUNDED_VALUE_as_0


SELECT 
	-10,
	ABS(-10) AS ABSOLUTE_VALUE

SELECT 
	-10,
	POWER(-10,3) AS POWER_VALUE

SELECT 
	-10,
	SQRT(10) AS POWER_VALUE
